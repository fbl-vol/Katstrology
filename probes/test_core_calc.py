from datetime import datetime, timedelta, timezone
from pathlib import Path
import unittest

import swisseph as swe

from core_calc import (aspect_separation, local_instant, solar_crossings,
                       solar_interval, solar_longitude)
from chart_probe import difference_degrees


UTC = timezone.utc
EQUINOX = datetime(2024, 3, 20, 3, 6, tzinfo=UTC)  # USNO published minute


class CoreCalculationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        swe.set_ephe_path(str((Path(__file__).resolve().parents[1] / '.local/ephe').resolve()))

    def test_solar_transit_crosses_published_march_equinox(self):
        # Independent USNO season table, not an output generated by this probe.
        start = datetime(2024, 3, 19, tzinfo=UTC)
        end = datetime(2024, 3, 21, tzinfo=UTC)
        events = solar_crossings(start, end, 0)
        self.assertEqual(len(events), 1)
        self.assertLess(abs(events[0] - EQUINOX), timedelta(minutes=3))
        self.assertEqual(solar_crossings(start, end, 90), [])
        # Natal 300° has a forward sextile target at 0°; no event at 240°.
        sextiles = solar_crossings(start, end, 300, 'sextile')
        self.assertEqual(len(sextiles), 1)
        self.assertLess(abs(sextiles[0] - EQUINOX), timedelta(minutes=3))
        self.assertLess(abs(difference_degrees(solar_longitude(EQUINOX), 0)), 0.05)
        # A crossing exactly on a scan boundary must not also return the
        # neighboring bisection's within-tolerance approximation.
        boundary = solar_crossings(EQUINOX - timedelta(hours=6), EQUINOX + timedelta(hours=6),
                                   solar_longitude(EQUINOX))
        self.assertEqual(len(boundary), 1)
        self.assertLess(abs(boundary[0] - EQUINOX), timedelta(minutes=1))

    def test_aspect_geometry_is_not_a_claim_about_orbs(self):
        self.assertAlmostEqual(aspect_separation(359, 1, 'conjunction'), 2)
        self.assertAlmostEqual(aspect_separation(15, 105, 'square'), 0)
        self.assertAlmostEqual(aspect_separation(10, 190, 'opposition'), 0)
        with self.assertRaisesRegex(ValueError, 'Unsupported aspect'):
            aspect_separation(0, 30, 'semisquare')

    def test_unknown_time_reports_crossing_sign_and_no_houses(self):
        result = solar_interval(EQUINOX - timedelta(hours=12), EQUINOX + timedelta(hours=12))
        self.assertIsNone(result['stable_sign'])
        self.assertEqual(result['houses'], 'unsupported_without_verified_birth_time')
        self.assertIsNone(result['reference_time'])
        stable = solar_interval(EQUINOX + timedelta(days=2), EQUINOX + timedelta(days=3))
        self.assertEqual(stable['stable_sign'], 0)

    def test_local_time_fold_gap_and_zone_conversion(self):
        self.assertEqual(local_instant(datetime(2024, 3, 20, 4, 6), 'Europe/Copenhagen'), EQUINOX)
        with self.assertRaisesRegex(ValueError, 'Nonexistent'):
            local_instant(datetime(2024, 3, 31, 2, 30), 'Europe/Copenhagen')
        wall = datetime(2024, 10, 27, 2, 30)
        with self.assertRaisesRegex(ValueError, 'Ambiguous'):
            local_instant(wall, 'Europe/Copenhagen')
        self.assertEqual(local_instant(wall, 'Europe/Copenhagen', 0),
                         datetime(2024, 10, 27, 0, 30, tzinfo=UTC))
        self.assertEqual(local_instant(wall, 'Europe/Copenhagen', 1),
                         datetime(2024, 10, 27, 1, 30, tzinfo=UTC))

    def test_range_and_missing_files_fail_explicitly(self):
        for year in (1900, 2099):
            self.assertGreaterEqual(solar_longitude(datetime(year, 6, 1, tzinfo=UTC)), 0)
        for year in (1800, 2100):
            with self.assertRaisesRegex(ValueError, 'Unsupported date'):
                solar_longitude(datetime(year, 1, 1, tzinfo=UTC))
        with self.assertRaisesRegex(ValueError, 'Unsupported event window'):
            solar_crossings(EQUINOX, EQUINOX + timedelta(days=31), 0)
        with self.assertRaisesRegex(ValueError, 'Unsupported solar interval'):
            solar_interval(EQUINOX, EQUINOX + timedelta(days=2))
        try:
            import tempfile
            with tempfile.TemporaryDirectory() as directory:
                swe.set_ephe_path(directory)
                with self.assertRaisesRegex(RuntimeError, 'fallback'):
                    solar_longitude(EQUINOX)
        finally:
            swe.set_ephe_path(str((Path(__file__).resolve().parents[1] / '.local/ephe').resolve()))


if __name__ == '__main__':
    unittest.main()
