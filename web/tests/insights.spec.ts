import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const renders = resolve(import.meta.dirname, '../../.local/saved-insights');
test.beforeAll(() => mkdirSync(renders, { recursive: true }));

test('explicit passage save, notebook edit/removal and original discussion stay separate', async ({ page }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 1440, height: 1024 });
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await page.goto('/');
  await page.getByLabel('Username').fill('reader-notebook');
  await page.getByLabel('Password').fill('synthetic-browser-password');
  await page.getByRole('button', { name: 'Open workspace' }).click();
  await expect(page.getByRole('heading', { name: 'What’s on your mind?' })).toBeVisible();
  await page.getByRole('button', { name: 'Add person', exact: true }).click();
  const newPerson = page.getByRole('dialog', { name: 'A space for someone new.' });
  await newPerson.getByLabel('Name').fill('Synthetic notebook reader');
  await newPerson.getByRole('button', { name: 'Create person' }).click();
  await page.getByRole('tab', { name: 'Basic info' }).click();
  await page.getByRole('button', { name: 'New conversation about Synthetic notebook reader' }).click();
  await page.getByLabel('Message Kat').fill('I collect synthetic sky sketches.');
  await page.getByRole('button', { name: 'Send message' }).click();
  const turn = page.locator('.turn-card').last();
  await expect(turn).toHaveAttribute('data-kat-status', 'complete', { timeout: 60000 });
  await turn.getByRole('button', { name: 'Save passage' }).click();
  const picker = page.getByRole('dialog', { name: 'Save conversation passage' });
  await expect(picker.getByLabel('For person')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(picker).toBeHidden();
  await expect(turn.getByRole('button', { name: 'Save passage' })).toBeFocused();
  await turn.getByRole('button', { name: 'Save passage' }).click();
  await expect(picker.getByLabel('For person')).toBeFocused();
  await expect(picker.getByLabel('For person')).toHaveValue(/p-/);
  const original = picker.getByLabel('Original archived wording');
  await expect(original).toHaveValue('I collect synthetic sky sketches.');
  await original.evaluate(node => (node as HTMLTextAreaElement).setSelectionRange(10, 32));
  await picker.getByRole('button', { name: 'Use selected text' }).click();
  await expect(picker.locator('blockquote')).toHaveText('synthetic sky sketches');
  await picker.getByLabel('Optional personal note').fill('A deliberate personal note, not a chart result.');
  await picker.getByRole('button', { name: 'Save for this person' }).click();
  await expect(picker).toBeHidden();
  await page.getByRole('navigation', { name: 'People' }).getByRole('button', { name: /Synthetic notebook reader/ }).click();
  await page.getByRole('tab', { name: 'Insights' }).click();
  const notebook = page.locator('.insight-notebook');
  await expect(notebook.getByText('synthetic sky sketches', { exact: true })).toBeVisible();
  await expect(notebook).toContainText('Current source');
  await expect(notebook).toContainText('A deliberate personal note, not a chart result.');
  await page.getByRole('button', { name: 'Settings' }).click();
  await page.getByRole('button', { name: /Appearance/ }).click();
  await page.getByRole('region', { name: 'Appearance' }).getByRole('button', { name: /Peony/ }).click();
  await page.getByRole('button', { name: 'Close settings panel' }).click();
  await page.getByRole('button', { name: 'Back to workspace' }).click();
  await expect(notebook.getByText('synthetic sky sketches', { exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(renders, 'notebook-desktop.png') });
  await notebook.getByRole('button', { name: 'Open original discussion' }).click();
  await expect(page.locator('.turn-card').last()).toContainText('I collect synthetic sky sketches.');
  await page.getByLabel('Message Kat').fill('Unsent follow-up remains a draft.');
  await page.getByRole('navigation', { name: 'People' }).getByRole('button', { name: /Synthetic notebook reader/ }).click();
  await page.getByRole('tab', { name: 'Insights' }).click();
  await expect(notebook.getByText('synthetic sky sketches', { exact: true })).toBeVisible();
  await notebook.getByRole('button', { name: 'Edit note' }).click();
  await notebook.getByLabel('Personal note').fill('Revised human annotation.');
  await notebook.getByRole('button', { name: 'Save note' }).click();
  await expect(notebook).toContainText('Revised human annotation.');
  await page.getByRole('button', { name: 'Settings' }).click();
  await page.getByRole('button', { name: /Appearance/ }).click();
  await page.getByRole('region', { name: 'Appearance' }).getByRole('button', { name: 'Dark', exact: true }).click();
  await page.getByRole('region', { name: 'Appearance' }).getByRole('button', { name: /Midnight Orchid/ }).click();
  await page.getByRole('button', { name: 'Close settings panel' }).click();
  await page.getByRole('button', { name: 'Back to workspace' }).click();
  await expect(notebook).toContainText('Revised human annotation.');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(renders, 'notebook-mobile.png') });
  await page.setViewportSize({ width: 390, height: 560 });
  await page.screenshot({ path: resolve(renders, 'notebook-short-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391);
  await page.setViewportSize({ width: 320, height: 568 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(321);
  page.once('dialog', dialog => dialog.accept());
  await notebook.getByRole('button', { name: 'Remove insight' }).click();
  await expect(notebook).toContainText('No saved passages for this person yet.');
  await page.reload();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation', { name: 'People' }).getByRole('button', { name: /Synthetic notebook reader/ }).click();
  await page.getByRole('tab', { name: 'Insights' }).click();
  await expect(page.locator('.insight-entry')).toHaveCount(0);
});
